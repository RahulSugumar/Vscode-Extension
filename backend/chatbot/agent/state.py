"""Typed state shared by the agent service and LangGraph-ready runner."""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Literal

from pydantic import BaseModel, Field


TriageClass = Literal["smalltalk", "meta", "clarification", "cache_hit", "task"]
AgentPath = Literal["fast", "full"]
# Keep plan actions closed so planner output can be validated before execution.
PlanAction = Literal[
    "query_codegraph",
    "query_project_inventory",
    "reason",
    "summarize",
    "compare",
    "ask_clarification",
    "reject_unrelated",
]


class Turn(BaseModel):
    """One persisted chat message as it appears in a layered history window."""

    role: Literal["user", "assistant"]
    content: str
    metadata: dict[str, Any] = Field(default_factory=dict)
    created_at: str | None = None


class LayeredWindow(BaseModel):
    """Bounded conversation context passed into planning and composing."""

    # This shape matches the long-term design: recent verbatim turns plus
    # compressed memory layers, instead of sending an unbounded transcript.
    verbatim: list[Turn] = Field(default_factory=list)
    summary: str | None = None
    pinned_facts: list[str] = Field(default_factory=list)
    window_token_estimate: int | None = None


class PlanStep(BaseModel):
    """One executable planner instruction.

    `depends_on` allows the executor to preserve order when a later step needs
    evidence generated by an earlier step.
    """

    id: str
    action: PlanAction
    instruction: str
    depends_on: list[str] = Field(default_factory=list)
    metadata: dict[str, Any] = Field(default_factory=dict)


class Plan(BaseModel):
    """Validated list of work items produced by the planner."""

    steps: list[PlanStep] = Field(default_factory=list)
    metadata: dict[str, Any] = Field(default_factory=dict)


class StepArtifact(BaseModel):
    """Output from one executor step, including tool/LLM metadata."""

    step_id: str
    action: PlanAction
    output: str
    error: str | None = None
    truncated: bool = False
    metadata: dict[str, Any] = Field(default_factory=dict)


class TriageDecision(BaseModel):
    """Fast/full routing decision returned before the agent graph runs."""

    triage_class: TriageClass
    path: AgentPath
    cached_answer: str | None = None
    reason: str


class AgentState(BaseModel):
    """Mutable state passed through the full LangGraph path.

    Nodes enrich this object in sequence: ingest adds history, plan adds steps,
    execute adds artifacts, critique marks completion, and compose writes the
    final markdown response.
    """

    user_id: str
    session_id: str
    user_text: str
    triage_class: TriageClass | None = None
    path: AgentPath | None = None
    window: LayeredWindow | None = None
    plan: Plan | None = None
    scratchpad: list[StepArtifact] = Field(default_factory=list)
    response_md: str | None = None
    done: bool = False
    iteration_count: int = 0
    max_iterations: int = 2
    critique_complete: bool = False
    critique_confidence: float | None = None
    critique_missing: str | None = None
    last_scratchpad_hash: str | None = None
    summary_refresh_requested: bool = False
    metrics: dict[str, Any] = Field(default_factory=dict)
    errors: list[str] = Field(default_factory=list)
    telemetry_events: list[dict[str, Any]] = Field(default_factory=list)


class AgentResult(BaseModel):
    """Small response object returned by `AgentService` to the API layer."""

    answer: str
    path: AgentPath
    triage_class: TriageClass


class AgentStreamEvent(BaseModel):
    """One incremental event emitted by `AgentService.stream_chat`."""

    event: Literal["start", "status", "chunk", "done", "error"]
    data: dict[str, Any] = Field(default_factory=dict)


def record_telemetry_event(
    state: AgentState,
    *,
    kind: str,
    node_id: str,
    message: str = "",
    **fields: Any,
) -> None:
    """Append a structured event used by ABKB turn-log telemetry."""

    state.telemetry_events.append(
        {
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "kind": kind,
            "node_id": node_id,
            "message": message,
            **fields,
        }
    )
